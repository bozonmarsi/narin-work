-- Различаем, откуда взялось соответствие: сама ли модель подобрала
-- (is_manual = false) или его подтвердил человек — вручную вписал в
-- форму, нажал "Запомнить соответствие" в результатах поиска, или
-- подтвердил при разборе фактуры (is_manual = true). Раньше ЛЮБОЕ
-- соответствие безусловно стиралось и переписывалось на каждом
-- прогоне vanvliet-alias-refresh — значит ручная правка держалась ровно
-- до следующего запуска, а потом молча исчезала. Человеческое
-- подтверждение теперь untouchable для автопрогона.
alter table product_name_aliases
  add column if not exists is_manual boolean not null default false;

-- Всё, что уже есть в базе на момент этой миграции, появилось либо от
-- ИИ (vanvliet-alias-refresh), либо руками через кнопку "Запомнить
-- соответствие" в поиске (rememberAlias) — вперёд оба места сами
-- проставляют is_manual правильно, а для уже накопленного считаем
-- честно "не знаем откуда", то есть не трогаем default false. Это
-- безопасно: хуже не станет, просто не даёт задним числом иммунитет
-- старым записям, которые и так пока не жаловались.
