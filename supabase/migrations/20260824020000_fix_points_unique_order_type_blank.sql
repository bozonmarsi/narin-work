-- unique_order_type UNIQUE(order_id, type) — старое ограничение (создано
-- ещё до этого репозитория), задумано как "нельзя дважды начислить
-- welcome-бонус за один и тот же заказ": у каждого реального заказа свой
-- уникальный order_id, так что это работало нормально.
--
-- Но claim_welcome_points (бонус при регистрации, ещё до первого заказа) и
-- ручное начисление баллов менеджером на странице "Баллы" оба всегда пишут
-- order_id = '' (пустая строка, чтобы в кабинете клиента не показывалось
-- "заказ №null"). Из-за этого ограничение по факту разрешает ТОЛЬКО ОДНУ
-- такую запись за всю историю проекта (первую, кто её создал) — все
-- следующие регистрации/ручные начисления с пустым order_id тихо
-- проваливались. Именно поэтому один тестовый email получил
-- приветственные баллы, а следующий — уже нет.
--
-- Сужаем ограничение так, чтобы оно защищало только настоящие заказы
-- (order_id не пустой), а не пустые записи — их от повторов и так
-- защищает points_transactions_one_welcome_per_email (по email).
ALTER TABLE points_transactions DROP CONSTRAINT IF EXISTS unique_order_type;

CREATE UNIQUE INDEX IF NOT EXISTS unique_order_type
  ON points_transactions (order_id, type)
  WHERE order_id IS NOT NULL AND order_id <> '';
