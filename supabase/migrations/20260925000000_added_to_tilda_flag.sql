-- Каталог у покупателя живёт в самой Tilda, отдельно от этой базы —
-- добавить товар тут (склад/рецепт/остаток) не значит, что он появился
-- на сайте, карточку в Tilda всё равно нужно завести руками (см. живые
-- баги: Kala picasso и Lilie růžová mix — оба были заведены только тут,
-- второй ещё и с опечаткой). Раньше это никак не отслеживалось и
-- забывалось. Новый товар теперь по умолчанию "не добавлен в Tilda" —
-- менеджер явно отмечает, когда карточку завёл на сайте.
ALTER TABLE product_stickers ADD COLUMN IF NOT EXISTS added_to_tilda boolean NOT NULL DEFAULT false;

-- Всё, что уже есть в базе на момент этой миграции, уже давно на
-- сайте — задним числом помечать это "не добавлено" было бы неверно и
-- завалило бы Каталог предупреждениями по всем старым товарам.
UPDATE product_stickers SET added_to_tilda = true;
