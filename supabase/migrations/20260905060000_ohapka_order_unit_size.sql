-- В Tilda охапки продаются "весовым" товаром — в заказе приходит
-- количество ЕДИНИЦ ("1"), а не стеблей, при этом сколько стеблей в
-- одной единице задано в самом Tilda ("Количество единицы товара") и
-- разное у разных охапок (5, 10, 25...). Без этого множителя сборка
-- списывала бы 1 стебель вместо, например, 10.
ALTER TABLE product_stickers ADD COLUMN IF NOT EXISTS order_unit_size int NOT NULL DEFAULT 1;
